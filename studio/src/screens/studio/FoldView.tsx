import { useEffect, useState, type KeyboardEvent, type ReactNode } from 'react';
import { t } from '../../i18n';
import { Rich } from '../rich';
import {
  cachedView, foldLevelFromKey, foldLevelLabel, foldOriginal, foldView, isFoldable, rememberedLevel, rememberLevel,
  FoldError, type FoldItem, type FoldLevel, type FoldView as View,
} from './fold-api';
import './fold.css';

const LEVELS: FoldLevel[] = [1, 2, 3, 4, 5];

type State =
  | { status: 'loading' }
  | { status: 'ready'; view: View }
  | { status: 'error'; message: string; modelUnavailable: boolean };

/** The original text a folded fragment came from, fetched when it is opened. */
function Original({ text, selector, plain }: { text: string; selector: { section?: string; paragraph?: string }; plain: boolean }) {
  const [original, setOriginal] = useState<string | null>(null);
  const [failed, setFailed] = useState(false);
  useEffect(() => {
    const controller = new AbortController();
    foldOriginal(text, selector, controller.signal).then(setOriginal).catch(() => { if (!controller.signal.aborted) setFailed(true); });
    return () => controller.abort();
  }, [text, selector.section, selector.paragraph]); // eslint-disable-line react-hooks/exhaustive-deps
  if (failed) return <p className="fs-fold__note" role="alert">{t('The original could not be opened.')}</p>;
  if (original === null) return <p className="fs-fold__note" role="status">{t('Opening…')}</p>;
  return <div className="fs-fold__original" data-testid="fold-original">{plain ? <pre className="fs-studio__out">{original}</pre> : <Rich text={original} />}</div>;
}

function Fragment({ text, item, plain }: { text: string; item: FoldItem; plain: boolean }) {
  const [open, setOpen] = useState(false);
  const selector = item.paragraph ? { paragraph: item.paragraph } : { section: item.section };
  const label = item.paragraph ? t('Open the original paragraph') : t('Open the original section');
  return (
    <li className="fs-fold__item" data-testid="fold-item" data-paragraph={item.paragraph} data-section={item.section}>
      <div className="fs-fold__fragment">{plain ? <pre className="fs-fold__plain">{item.text}</pre> : <Rich text={item.text} />}</div>
      <button type="button" className="fs-link fs-fold__open" aria-expanded={open} aria-label={label} title={label} data-testid="fold-open" onClick={() => setOpen(!open)}>
        {open ? t('Hide the original') : t('Original')}
      </button>
      {open && <Original text={text} selector={selector} plain={plain} />}
    </li>
  );
}

function Topics({ text, items, plain }: { text: string; items: FoldItem[]; plain: boolean }) {
  const [open, setOpen] = useState<number | null>(null);
  return (
    <ul className="fs-fold__cards" data-testid="fold-topics">
      {items.map((card) => (
        <li key={card.topic} className="fs-fold__card" data-testid="fold-card">
          <button type="button" className="fs-fold__card-head" aria-expanded={open === card.topic} onClick={() => setOpen(open === card.topic ? null : card.topic ?? null)}>
            <strong>{card.title}</strong>
            <span>{card.text.slice((card.title?.length ?? 0) + 2)}</span>
          </button>
          {open === card.topic && (card.sections ?? []).map((section) => <Original key={section} text={text} selector={{ section }} plain={plain} />)}
        </li>
      ))}
    </ul>
  );
}

function Body({ text, view, plain }: { text: string; view: View; plain: boolean }) {
  if (view.level === 5) return <Topics text={text} items={view.items} plain={plain} />;
  return (
    <ol className="fs-fold__list" data-testid="fold-view" data-level={view.level}>
      {view.items.map((item) => <Fragment key={item.paragraph ?? item.section} text={text} item={item} plain={plain} />)}
    </ol>
  );
}

/**
 * A long text shown at one of five levels of detail: full, literal key
 * sentences, key idea, one line per section, topics. Digits 1-5 (with the
 * block focused) or the slider choose the level. Levels 3-5 are generated by
 * the model on demand; when it does not answer, the notice says so and the
 * deterministic levels stay available.
 */
export function Foldable({ text, active = true, plain = false, children }: {
  text: string;
  /** False while the text is still streaming in: nothing to fold yet. */
  active?: boolean;
  /** Tool output is not Markdown: fragments are shown verbatim. */
  plain?: boolean;
  children: ReactNode;
}) {
  const foldable = active && isFoldable(text);
  // A row rebuilt by the transcript (scrolling, a history reload) comes back at the level it was left at.
  const [level, setLevelState] = useState<FoldLevel>(() => (foldable ? rememberedLevel(text) : 1));
  const [state, setState] = useState<State>(() => {
    const view = foldable ? cachedView(text, rememberedLevel(text)) : undefined;
    return view ? { status: 'ready', view } : { status: 'loading' };
  });
  const setLevel = (next: FoldLevel) => { rememberLevel(text, next); setLevelState(next); };
  const [retries, setRetries] = useState(0);

  useEffect(() => {
    if (!foldable || level === 1) return;
    const controller = new AbortController();
    const known = cachedView(text, level);
    setState(known ? { status: 'ready', view: known } : { status: 'loading' });
    if (known && retries === 0) return;
    foldView(text, level, controller.signal)
      .then((view) => setState({ status: 'ready', view }))
      .catch((error: unknown) => {
        if (controller.signal.aborted) return;
        setState({
          status: 'error',
          message: error instanceof Error ? error.message : String(error),
          modelUnavailable: error instanceof FoldError && error.modelUnavailable,
        });
      });
    return () => controller.abort();
  }, [text, level, foldable, retries]); // eslint-disable-line react-hooks/exhaustive-deps

  if (!foldable) return <>{children}</>;

  const onKeyDown = (event: KeyboardEvent<HTMLDivElement>) => {
    const target = event.target as HTMLElement;
    if (event.ctrlKey || event.metaKey || event.altKey) return;
    if (target.closest('input[type="text"], textarea, [contenteditable="true"], select')) return;
    const next = foldLevelFromKey(event.key);
    if (next) { event.preventDefault(); setLevel(next); }
  };
  const retry = () => setRetries((n) => n + 1);

  return (
    <div className="fs-fold" data-testid="fold" data-level={level} tabIndex={0} aria-keyshortcuts="1 2 3 4 5" aria-label={t('Long text. Press 1 to 5 to change the level of detail.')} onKeyDown={onKeyDown}>
      <div className="fs-fold__bar" role="group" aria-label={t('Level of detail')}>
        <input
          type="range" min={1} max={5} step={1} value={level}
          className="fs-fold__slider" data-testid="fold-slider"
          aria-label={t('Level of detail')} aria-valuetext={foldLevelLabel(level)}
          onChange={(event) => setLevel(Number(event.target.value) as FoldLevel)}
        />
        <span className="fs-fold__ticks" aria-hidden="true">{LEVELS.map((n) => <button key={n} type="button" tabIndex={-1} className="fs-fold__tick" data-active={n === level} onClick={() => setLevel(n)}>{n}</button>)}</span>
        <span className="fs-fold__name" data-testid="fold-name" aria-live="polite">{foldLevelLabel(level)}</span>
        {level > 1 && state.status === 'ready' && (
          <span className="fs-fold__size" data-testid="fold-size">{t('{shown} of {total} characters', { shown: state.view.chars, total: state.view.original_chars })}</span>
        )}
      </div>
      {level === 1 && children}
      {level > 1 && state.status === 'loading' && <p className="fs-fold__note" role="status">{level > 2 ? t('Writing this level…') : t('Folding…')}</p>}
      {level > 1 && state.status === 'error' && (
        <p className="fs-fold__note" role="alert" data-testid="fold-error">
          {state.modelUnavailable ? t('The model is not answering, so this level cannot be written now. Levels 1 and 2 still work.') : state.message}
          {' '}
          <button type="button" className="fs-link" onClick={retry}>{t('Try again')}</button>
          {level > 2 && <> <button type="button" className="fs-link" onClick={() => setLevel(2)}>{foldLevelLabel(2)}</button></>}
        </p>
      )}
      {level > 1 && state.status === 'ready' && state.view.level === level && <Body text={text} view={state.view} plain={plain} />}
    </div>
  );
}
