import assert from 'node:assert/strict';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {dirname,resolve,join} from 'node:path';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..','..');
const {build}=await import(pathToFileURL(join(root,'node_modules/esbuild/lib/main.js')));
const output=join(mkdtempSync(join(tmpdir(),'fs-selection-')),'selection.mjs');
await build({entryPoints:[join(root,'studio/src/adapters/model-selection.ts')],bundle:true,format:'esm',platform:'node',outfile:output,logLevel:'silent'});
const {chooseStudioRoute,configuredDefaultRoute}=await import(pathToFileURL(output));
const pc={id:'pc::historical-model',model:'historical-model',endpointId:'pc',endpointName:'PC',endpointUrl:'http://fixture-pc',kind:'local'};
const spark={id:'spark::global-model',model:'global-model',endpointId:'spark',endpointName:'Sparks',endpointUrl:'http://fixture-spark',kind:'configured-default',missing:true};
assert.equal(chooseStudioRoute([pc],null,{},null,false),null,'pending default must not select the first PC route');
assert.equal(chooseStudioRoute([pc],null,{},spark,true).id,spark.id);
assert.equal(chooseStudioRoute([pc],null,{},spark,true).missing,true);
assert.equal(chooseStudioRoute([pc,{...pc,id:'pc::global-model',model:'global-model'}],null,{},spark,true).endpointId,'spark','same name on another endpoint is not the configured service');
assert.equal(chooseStudioRoute([pc],pc.id,pc,spark,true).id,pc.id,'manual choices remain available');
const recovered={...spark,missing:false,kind:'local'};
assert.equal(chooseStudioRoute([pc,recovered],null,{},spark,true),recovered);
globalThis.fetch=async()=>new Response(JSON.stringify({endpoint_id:'spark',model:'global-model',endpoint_url:'http://fixture-spark',missing:true}));
assert.equal((await configuredDefaultRoute()).missing,true);
console.log('PASS configured global selection, pending read, unavailable model, manual choice and recovery.');
