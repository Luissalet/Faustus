import assert from 'node:assert/strict';
import {pathToFileURL, fileURLToPath} from 'node:url';
import {dirname, resolve, join} from 'node:path';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const {build} = await import(pathToFileURL(join(root, 'node_modules/esbuild/lib/main.js')));
async function load(entry) {
  const out = join(mkdtempSync(join(tmpdir(), 'continuity711-')), 'check.mjs');
  await build({entryPoints:[join(root, entry)], bundle:true, format:'esm', platform:'node', outfile:out, logLevel:'silent'});
  return import(pathToFileURL(out));
}
const {apply, blankTurn} = await load('studio/src/screens/studio/model.ts');
const {roomView} = await load('studio/src/screens/group/room-model.ts');
let turn = apply(blankTurn('assistant'), {type:'delta', text:'Original answer', thinking:false});
turn = apply(turn, {type:'response_replace', text:''});
assert.equal(turn.text, 'Original answer', 'a new drafting round must not erase the visible answer');
turn = apply(turn, {type:'delta', text:'Revised', thinking:false});
assert.equal(turn.text, 'Original answer', 'an unfinished revision stays buffered');
turn = apply(turn, {type:'response_replace', text:''});
turn = apply(turn, {type:'delta', text:'Final answer', thinking:false});
assert.equal(turn.text, 'Original answer', 'repeated retries preserve the displayed draft');
turn = apply(turn, {type:'done'});
assert.equal(turn.text, 'Final answer');
assert.equal(turn.replacementText, undefined);
let replaced = apply(turn, {type:'response_replace', text:'Canonical answer'});
assert.equal(replaced.text, 'Canonical answer', 'an explicit complete replacement is authoritative');
replaced = apply(replaced, {type:'response_replace', text:''});
replaced = apply(replaced, {type:'error', message:'Provider failed'});
replaced = apply(replaced, {type:'done'});
assert.equal(replaced.text, 'Canonical answer');
assert.equal(replaced.error, 'Provider failed');
const step = {id:'s', turn_id:'t', member_id:'a', status:'running', text:'Original answer', error:'', detail:{}};
const snapshot = {group:{parentId:'g', participants:[]}, busy:true, turns:[{id:'t', message:'Question', status:'running'}], steps:[step]};
assert.equal(roomView([], snapshot, {}).turns.at(-1).text, 'Original answer', 'a snapshot remains visible before the live stream attaches');
assert.equal(roomView([], snapshot, {s:blankTurn('assistant')}).turns.at(-1).text, 'Original answer', 'a stream handshake cannot blank the snapshot');
let resumed = blankTurn('assistant');
for (const event of [{type:'delta', text:'Original answer', thinking:false}, {type:'response_replace', text:''}, {type:'delta',text:'New partial',thinking:false}]) resumed=apply(resumed,event);
step.text = 'New partial';
assert.equal(roomView([], snapshot, {s:resumed}).turns.at(-1).text, 'Original answer', 'the native full replay restores the visible draft when reopening during revision');
step.status = 'done'; step.text = 'Canonical answer';
assert.equal(roomView([], snapshot, {s:turn}).turns.at(-1).text, 'Canonical answer', 'terminal steps supersede stale live text before history is loaded');
const history = [{role:'assistant', content:'Canonical answer', index:0, metadata:{group_step_id:'s'}}];
assert.equal(roomView(history, snapshot, {s:turn}).turns.filter(t=>t.role==='assistant').length, 1);
console.log('PASS: drafting, repeated reset, explicit replacement, failure, reopen and canonical handoff.');
