import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { Window } from 'happy-dom';

const window = new Window({ url: 'http://localhost/projects/p' });
for (const key of ['window', 'document', 'navigator', 'HTMLElement', 'MutationObserver', 'Event', 'CustomEvent', 'getComputedStyle']) Object.defineProperty(globalThis, key, { configurable: true, value: key === 'getComputedStyle' ? window.getComputedStyle.bind(window) : key === 'window' ? window : window[key] });
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
globalThis.requestAnimationFrame = (callback) => setTimeout(callback, 0);
globalThis.cancelAnimationFrame = clearTimeout;
const result = await build({ stdin: { contents: `export {projectSection, PROJECT_SECTIONS, ProjectNavigation} from './studio/src/screens/project/ProjectNavigation'; export {droppedFiles} from './studio/src/screens/project/Skills'; export {workspaceAction, skillFiles} from './studio/src/adapters/projectWorkspace'; export {filterIssues} from './studio/src/adapters/board'; export {createElement, act} from 'react'; export {createRoot} from 'react-dom/client'; export {MemoryRouter} from 'react-router';`, resolveDir: process.cwd(), loader: 'ts' }, bundle: true, format: 'esm', platform: 'node', write: false, loader: { '.css': 'empty' } });
const m = await import('data:text/javascript;base64,' + Buffer.from(result.outputFiles[0].text).toString('base64'));
assert.deepEqual(m.PROJECT_SECTIONS.map((s) => s.id), ['overview', 'chats', 'tasks', 'knowledge', 'skills', 'settings']);
for (const [legacy, expected] of Object.entries({brief:'overview',agora:'overview',board:'tasks',objetivos:'tasks',requisitos:'tasks',memoria:'knowledge',contexto:'knowledge',reglas:'settings',repos:'settings',ajustes:'settings',actividad:'overview'})) assert.equal(m.projectSection(legacy), expected);
assert.equal(m.projectSection('unknown'), 'overview');
const host = document.createElement('div'); document.body.append(host);
const root = m.createRoot(host);
let selected;
await m.act(async () => root.render(m.createElement(m.MemoryRouter, null, m.createElement(m.ProjectNavigation, { selected:'overview', onChange:(id) => {selected=id;}, projectId:'p', liveChats:0, liveTone:'running' }))));
assert.equal(host.querySelectorAll('[role="tab"]').length, 6);
assert.equal(host.querySelectorAll('[role="tablist"] button').length, 6, 'project tools do not masquerade as a seventh tab');
await m.act(async () => host.querySelector('[data-testid="project-tab-skills"]').click());
assert.equal(selected, 'skills');
const issues=[{id:'QA-1',title:'one',labels:['tag libre']},{id:'QA-2',title:'two',labels:['other']}];
assert.deepEqual(m.filterIssues(issues,{label:'tag libre'}).map((i) => i.id),['QA-1']);
let request;
globalThis.fetch=async (url, init) => { request={url,init}; return Response.json({ok:true}); };
await m.workspaceAction('a/b','skill_import',{content:'---\nname: test\n---'});
assert.equal(request.url,'/api/projects/a%2Fb/workspace/action');
assert.equal(JSON.parse(request.init.body).action,'skill_import');
globalThis.fetch=async () => Response.json({detail:'Changed since review'},{status:409});
await assert.rejects(m.workspaceAction('p','skill_activate',{key:'skill'}), /Changed since review/);
await assert.rejects(m.skillFiles(Array.from({length:65},() => ({size:1}))),/64/);
const dropFile = {name:'SKILL.md',size:10};
const fileEntry = {isFile:true,isDirectory:false,file:(resolve) => resolve(dropFile)};
let directoryRead = false;
const directory = {name:'local-skill',isFile:false,isDirectory:true,createReader:() => ({readEntries:(resolve) => { resolve(directoryRead ? [] : [fileEntry]); directoryRead=true; }})};
const dropped = await m.droppedFiles({items:[{webkitGetAsEntry:() => directory}]});
assert.equal(dropped.length,1);
assert.equal(dropped[0].webkitRelativePath,'local-skill/SKILL.md','folder drops retain bundle-relative paths');
await m.act(async () => root.unmount());
await window.happyDOM.abort();
console.log('ALL OK: six mounted sections, legacy links, free tags and real skill request/error transport');
process.exit(0);
