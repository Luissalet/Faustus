import assert from 'node:assert/strict';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const { build } = await import(pathToFileURL(join(root, 'node_modules/esbuild/lib/main.js')).href);
const output = join(mkdtempSync(join(tmpdir(), 'coordination-check-')), 'adapter.mjs');
await build({ entryPoints: [join(root, 'studio/src/adapters/coordination.ts')], bundle: true, platform: 'node',
  format: 'esm', outfile: output, logLevel: 'silent' });
const c = await import(pathToFileURL(output).href);
const template = { id:'template', project_id:'project', connector_id:'hub', actor:'faustus-private', revision:7,
  operations:['poll','task','claim','post'], resources:['path:repo','model:principal'], repos:['repo'], thread_ids:[55], active:true };
const folder = { label:'Repository', repo:'Repo', path:'D:/Projects/repo', resources:['path:Repo'] };
assert.equal(c.coordinationState({template:null, binding:null, usable:false, unavailable:null}), 'not_configured');
assert.equal(c.coordinationState({template, binding:null, usable:false, unavailable:null}), 'prepared');
assert.equal(c.coordinationState({template, binding:null, usable:true, unavailable:null}), 'available');
assert.equal(c.coordinationState({template, usable:false, unavailable:'connection closed'}), 'unavailable');
assert.equal(c.coordinationState({template:{...template,active:false}, binding:{...template,active:true}, usable:false, unavailable:'revoked'}), 'disabled');
assert(c.choiceSelected(template, folder), 'case differences do not clear a saved folder');
const selected = new Set([c.choiceKey(folder)]);
const unchanged = c.coordinationDraft(template,'hub',[folder],selected,true);
assert.deepEqual(unchanged.resources, template.resources);
assert.deepEqual(unchanged.repos, template.repos);
assert.deepEqual(unchanged.operations, template.operations, 'editing folders never widens the operation grant');
assert.deepEqual(unchanged.thread_ids,[55,32]);
assert.equal(unchanged.expected_revision,7);
assert(!('actor' in unchanged) && !('owner' in unchanged), 'identity comes only from the product');
const removed = c.coordinationDraft(template,'hub',[folder],new Set(),true);
assert.deepEqual(removed.resources,['model:principal'], 'folder removal preserves independent authorized resources');
assert.deepEqual(removed.repos,[]);
const narrow = {...template,resources:['path:repo/src','model:principal']};
const kept = c.coordinationDraft(narrow,'hub',[folder],new Set(),true);
assert.deepEqual(kept.resources,narrow.resources, 'a narrower saved folder absent from current choices is not silently removed');
assert.deepEqual(kept.repos,narrow.repos);
const switched = c.coordinationDraft(template,'other',[folder],selected,true);
assert.deepEqual(switched.resources,['path:Repo'], 'a different connection gets only the explicitly selected verified choices');
assert.deepEqual(switched.operations,template.operations);
let calls=[];
globalThis.fetch=async(path,options)=>{
  calls.push({path,options});
  return new Response(JSON.stringify({template:{...template,revision:8}}),{status:200,headers:{'Content-Type':'application/json'}});
};
await c.saveProjectCoordination('project/with space',unchanged);
assert.equal(calls[0].path,'/api/coordination/projects/project%2Fwith%20space');
assert.equal(calls[0].options.credentials,'same-origin');
assert.equal(JSON.parse(calls[0].options.body).expected_revision,7);
globalThis.fetch=async()=>new Response(JSON.stringify({detail:'newer revision'}),{status:409,headers:{'Content-Type':'application/json'}});
await assert.rejects(c.saveProjectCoordination('project',unchanged), error=>error.status===409);
console.log('Native coordination adapter: identity, revision, scope preservation, availability and HTTP verified');
